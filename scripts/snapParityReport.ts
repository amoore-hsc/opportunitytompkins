/**
 * Writes docs/snap-parity-report.md: how the new SNAP screener's results
 * compare with the old Google Form for every combination of answers.
 *
 *   npm run parity-report
 */
import { writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { SNAP_QUESTIONS, type SnapOutcome, type SnapQuestionKey } from "@/config/snapScreener";
import { evaluateOldForm, evaluateSnap, OLD_FORM_QUESTIONS, type SnapAnswers } from "@/lib/snapScreener";
import { isExempt, runParity } from "@/lib/snapParity";

const PAGE: Record<SnapOutcome, string> = {
  not_receiving: "Not receiving SNAP",
  exempt: "Exempt (nothing to do)",
  medical: "Medical Exemption (medical form)",
  caregiver: "Caregiver Exemption (caregiver form)",
  action_needed: "Action needed",
};

const text = Object.fromEntries(SNAP_QUESTIONS.map((q) => [q.key, q.text])) as Record<SnapQuestionKey, string>;
const short = (key: SnapQuestionKey) => text[key].replace(/^(Are|Do) you (currently )?/, "").replace(/\?$/, "");

const cases = runParity();
const enrolled = cases.filter((c) => c.answers.snap_enrolled);
const diffs = enrolled.filter((c) => c.oldOutcome !== c.newOutcome);
const exemptMismatch = enrolled.filter((c) => isExempt(c.oldOutcome) !== isExempt(c.newOutcome));

// Pairs: exactly two exemption questions answered Yes.
const exemptionKeys = SNAP_QUESTIONS.filter((q) => q.key !== "snap_enrolled").map((q) => q.key);
const pairRows: string[] = [];
for (let i = 0; i < exemptionKeys.length; i++) {
  for (let j = i + 1; j < exemptionKeys.length; j++) {
    const answers: SnapAnswers = { snap_enrolled: true };
    for (const k of exemptionKeys) answers[k] = k === exemptionKeys[i] || k === exemptionKeys[j];
    const oldOutcome = evaluateOldForm(answers);
    const state = evaluateSnap(answers);
    const newOutcome = state.status === "result" ? state.outcome : "action_needed";
    if (oldOutcome !== newOutcome) {
      pairRows.push(`| ${short(exemptionKeys[i])} | ${short(exemptionKeys[j])} | ${PAGE[oldOutcome]} | ${PAGE[newOutcome]} |`);
    }
  }
}

// Summary of which page changes.
const shifts = new Map<string, number>();
for (const c of diffs) {
  const k = `${PAGE[c.oldOutcome]} → ${PAGE[c.newOutcome]}`;
  shifts.set(k, (shifts.get(k) ?? 0) + 1);
}

const md = `# SNAP screener parity report

Generated by \`npm run parity-report\` from \`src/config/snapScreener.ts\`. Compares the new on-site
screener with the old Google Form ("SNAP Work Rules Screener") for **every** combination of Yes/No
answers to all ${SNAP_QUESTIONS.length} questions (${cases.length.toLocaleString()} combinations).

Both tools stop at the first answer that settles the result, so when **one** exemption applies the
result is always the same. They ask in a different order, so when **two or more** apply they can stop
on different questions and show a different page.

## Summary

| Check | Result |
|---|---|
| Combinations checked | ${cases.length.toLocaleString()} |
| "Not receiving SNAP" result matches | ${cases.every((c) => (c.oldOutcome === "not_receiving") === (c.newOutcome === "not_receiving")) ? "Yes, in every case" : "**NO**"} |
| Exempt vs. not exempt matches | ${exemptMismatch.length === 0 ? "Yes, in every case" : `**NO: ${exemptMismatch.length} cases**`} |
| Same page when 0 or 1 exemption applies | ${enrolled.filter((c) => c.yesKeys.length <= 2).every((c) => c.oldOutcome === c.newOutcome) ? "Yes, in every case" : "**NO**"} |
| Combinations (SNAP = Yes) where the page differs | ${diffs.length.toLocaleString()} of ${enrolled.length.toLocaleString()} |

Nobody is told they're exempt by one tool and "action needed" by the other. The only differences are
**which exempt page** someone sees, which decides whether they're asked to send in a form.

## How the page changes

| Old form page → New screener page | Combinations |
|---|---|
${[...shifts.entries()].sort((a, b) => b[1] - a[1]).map(([k, n]) => `| ${k} | ${n.toLocaleString()} |`).join("\n")}

## Two exemptions at once: every pair that differs

Someone answered Yes to exactly these two questions (and No to the rest):

| Yes to | And yes to | Old form shows | New screener shows |
|---|---|---|---|
${pairRows.join("\n")}

What changed and why:

- The new order follows SNAP guidance: when someone qualifies for more than one exemption, the one
  that lasts longest is applied, and New York checks "unfit for work" last, for people who don't
  qualify any other way. So the screener asks long-lasting, no-paperwork exemptions first and the
  form-based ones (treatment program, caregiving, health condition) last.
- Every difference above is someone who also has a no-paperwork exemption (working, unemployment
  benefits, or Indian Health Services eligibility, which the old form asked after the form-based
  questions). The new screener tells them they have nothing to do instead of sending them a form.
- One pair (caregiving plus a health condition) now shows the Caregiver page instead of the Medical
  page, because the health-condition question is asked last.
- No one is sent a form by the new screener that the old form would not have sent them.

**Owner sign-off:** confirm these differences are acceptable before turning on \`snapScreenerEnabled\`.

## Question order

| # | New screener | Old form # |
|---|---|---|
${SNAP_QUESTIONS.map((q, i) => `| ${i + 1} | ${q.text} | ${q.oldFormOrder} |`).join("\n")}

Old form order: ${OLD_FORM_QUESTIONS.map((q) => q.oldFormOrder + ". " + short(q.key)).join("; ")}.
`;

const out = path.resolve(process.cwd(), "docs/snap-parity-report.md");
mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(out, md);
console.log(`Wrote ${out}: ${diffs.length} of ${enrolled.length} combinations show a different page.`);
